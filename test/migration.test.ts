import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

for (const populated of [false, true]) {
  test(`profit category migration preserves existing ${populated ? 'populated' : 'empty'} display tables and is repeatable`, async () => {
    const db = new PGlite();
    try {
      for (const table of ['top_gainers', 'top_losers']) {
        await db.exec(`create table public.${table} (
          id bigint generated by default as identity primary key,
          name text, price numeric, change numeric, change_percent numeric, updated_at timestamptz
        )`);
        if (populated) {
          await db.exec(`insert into public.${table}(name, price, change, change_percent, updated_at)
            values ('preserved', 500, 100, 25, '2026-10-27T12:00:00Z')`);
        }
      }
      const before = await Promise.all(['top_gainers', 'top_losers'].map(table =>
        db.query(`select id, name, price, change, change_percent, updated_at from public.${table}`)));
      const sql = await readFile(new URL('../supabase/migrations/001_profit_probability.sql', import.meta.url), 'utf8');
      await db.exec(sql);
      await db.exec(sql);
      const reportsSql = await readFile(new URL('../supabase/migrations/002_report_url.sql', import.meta.url), 'utf8');
      await db.exec(reportsSql);
      await db.exec(reportsSql);
      for (const table of ['top_gainers', 'top_losers']) {
        const columns = await db.query<{ column_name: string }>(
          'select column_name from information_schema.columns where table_schema = $1 and table_name = $2 order by column_name',
          ['public', table],
        );
        assert.deepEqual(columns.rows.map(row => row.column_name),
          ['change', 'change_percent', 'id', 'name', 'price', 'profit_probability', 'report_url', 'updated_at']);
        assert.equal((await db.query(`select * from public.${table} where report_url is not null`)).rows.length, 0);
        await db.exec(`update public.${table} set report_url = 'https://reports.example.org/legacy.html'`);
      }
      assert.equal((await db.query("select * from information_schema.tables where table_name = 'stock_research_publications'")).rows.length, 0);
      assert.equal((await db.query("select proname from pg_proc where proname = 'publish_stock_research'")).rows.length, 0);
      const after = await Promise.all(['top_gainers', 'top_losers'].map(table =>
        db.query(`select id, name, price, change, change_percent, updated_at from public.${table}`)));
      assert.deepEqual(after.map(result => result.rows), before.map(result => result.rows));
      await db.exec("insert into public.top_gainers(profit_probability) values ('low'), ('medium'), ('high'), (null)");
      await assert.rejects(db.exec("insert into public.top_gainers(profit_probability) values ('certain')"), /check constraint/);
    } finally { await db.close(); }
  });
}
